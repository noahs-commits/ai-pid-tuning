"""Configuration objects for the 1D PID environment."""

from __future__ import annotations

from dataclasses import dataclass, field


@dataclass
class NoiseConfig:
    """Parameters for one fractal Perlin noise source."""

    seed: int = 0
    octaves: int = 4
    persistence: float = 0.5
    lacunarity: float = 2.0
    frequency: float = 1.0

    def __post_init__(self) -> None:
        if self.octaves < 1:
            raise ValueError("octaves must be >= 1")
        if not 0.0 < self.persistence <= 1.0:
            raise ValueError("persistence must be in (0, 1]")
        if self.lacunarity <= 0.0:
            raise ValueError("lacunarity must be > 0")
        if self.frequency <= 0.0:
            raise ValueError("frequency must be > 0")


@dataclass
class EnvironmentConfig:
    """Physical and episode settings for :class:`PID1DEnv`.

    The body moves along a single vertical axis.  Positive position is up and
    positive thrust pushes up.  At each step::

        accel = (thrust * action - weight + drag_force + disturbance) / mass
        drag_force = -drag * velocity

    All forces are in newtons, mass in kilograms, positions in metres and
    time in seconds.
    """

    # Time / episode
    dt: float = 0.02
    max_steps: int = 1000

    # Physics
    mass: float = 1.0
    weight: float = 9.81
    drag: float = 0.5
    thrust: float = 20.0

    # Setpoint and initial state
    target: float = 1.0
    initial_position: float = 0.0
    initial_velocity: float = 0.0

    # External disturbance force generated by fractal Perlin noise
    disturbance_strength: float = 0.0
    disturbance_frequency: float = 1.0
    disturbance_noise: NoiseConfig = field(default_factory=lambda: NoiseConfig(seed=0))

    # Optional moving setpoint generated by fractal Perlin noise
    target_noise_strength: float = 0.0
    target_noise_frequency: float = 0.5
    target_noise: NoiseConfig = field(default_factory=lambda: NoiseConfig(seed=1))

    # Episode termination when position leaves these bounds, if provided
    bounds: tuple[float, float] | None = None

    # Reward shaping: reward = -error^2 - control_cost * action^2
    reward_control_cost: float = 0.0

    def __post_init__(self) -> None:
        if self.dt <= 0.0:
            raise ValueError("dt must be > 0")
        if self.max_steps < 1:
            raise ValueError("max_steps must be >= 1")
        if self.mass <= 0.0:
            raise ValueError("mass must be > 0")
        if self.weight < 0.0:
            raise ValueError("weight must be >= 0")
        if self.drag < 0.0:
            raise ValueError("drag must be >= 0")
        if self.thrust < 0.0:
            raise ValueError("thrust must be >= 0")
        if self.disturbance_strength < 0.0:
            raise ValueError("disturbance_strength must be >= 0")
        if self.target_noise_strength < 0.0:
            raise ValueError("target_noise_strength must be >= 0")
        if self.bounds is not None and self.bounds[0] >= self.bounds[1]:
            raise ValueError("bounds must be (low, high) with low < high")
